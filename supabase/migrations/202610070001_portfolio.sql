create table if not exists public.projects (
  slug text primary key,
  name text not null,
  summary text not null,
  description text not null,
  categories text[] not null default '{}',
  technology_heading text,
  features text[] not null default '{}',
  contribution text,
  status text,
  planned text[] not null default '{}',
  metrics jsonb not null default '[]'::jsonb,
  related_project_slugs text[] not null default '{}',
  sort_order integer not null default 0,
  published boolean not null default true,
  constraint projects_categories_valid check (
    categories <@ array[
      'Featured', 'Full-stack', 'Frontend', 'Backend', 'AI', 'Data',
      'University', 'Personal', 'Startup'
    ]::text[]
  )
);

alter table public.projects
  add column if not exists technology_heading text;

create table if not exists public.technologies (
  id bigint generated by default as identity primary key,
  name text not null unique
);

create table if not exists public.project_technologies (
  project_slug text not null references public.projects(slug) on delete cascade,
  technology_id bigint not null references public.technologies(id) on delete cascade,
  sort_order integer not null default 0,
  primary key (project_slug, technology_id)
);

create table if not exists public.experiences (
  slug text primary key,
  organization text not null,
  role text not null,
  start_date date not null,
  end_date date,
  summary text not null,
  responsibilities text[] not null default '{}',
  sort_order integer not null default 0,
  published boolean not null default true
);

create table if not exists public.experience_technologies (
  experience_slug text not null references public.experiences(slug) on delete cascade,
  technology_id bigint not null references public.technologies(id) on delete cascade,
  sort_order integer not null default 0,
  primary key (experience_slug, technology_id)
);

create table if not exists public.project_images (
  id bigint generated by default as identity primary key,
  project_slug text not null references public.projects(slug) on delete cascade,
  src text not null,
  alt text not null,
  caption text,
  sort_order integer not null default 0
);

create table if not exists public.events (
  slug text primary key,
  name text not null,
  organization text not null,
  type text not null,
  date_label text,
  description text not null,
  learning text[] not null default '{}',
  people jsonb not null default '[]'::jsonb,
  related_project_slug text references public.projects(slug) on delete set null,
  sort_order integer not null default 0,
  published boolean not null default true
);

create table if not exists public.event_tags (
  id bigint generated by default as identity primary key,
  event_slug text not null references public.events(slug) on delete cascade,
  tag text not null,
  sort_order integer not null default 0,
  unique (event_slug, tag)
);

create table if not exists public.links (
  id bigint generated by default as identity primary key,
  entity_type text not null check (entity_type in ('project', 'experience', 'event', 'profile')),
  entity_slug text,
  kind text not null,
  label text not null,
  url text not null,
  sort_order integer not null default 0
);

