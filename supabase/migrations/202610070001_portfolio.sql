alter table public.event_tags enable row level security;
alter table public.links enable row level security;

drop policy if exists "Public can read published projects" on public.projects;
create policy "Public can read published projects" on public.projects
  for select to anon, authenticated using (published);
drop policy if exists "Public can read technologies" on public.technologies;
create policy "Public can read technologies" on public.technologies
  for select to anon, authenticated using (true);
drop policy if exists "Public can read project technologies" on public.project_technologies;
create policy "Public can read project technologies" on public.project_technologies
  for select to anon, authenticated using (
    exists (
      select 1 from public.projects
      where projects.slug = project_technologies.project_slug and projects.published
    )
  );
drop policy if exists "Public can read experience technologies" on public.experience_technologies;
create policy "Public can read experience technologies" on public.experience_technologies
  for select to anon, authenticated using (
    exists (
      select 1 from public.experiences
      where experiences.slug = experience_technologies.experience_slug and experiences.published
    )
  );
drop policy if exists "Public can read project images" on public.project_images;
create policy "Public can read project images" on public.project_images
  for select to anon, authenticated using (
    exists (
      select 1 from public.projects
      where projects.slug = project_images.project_slug and projects.published
    )
  );
drop policy if exists "Public can read published experiences" on public.experiences;
create policy "Public can read published experiences" on public.experiences
  for select to anon, authenticated using (published);
drop policy if exists "Public can read published events" on public.events;
create policy "Public can read published events" on public.events
  for select to anon, authenticated using (published);
drop policy if exists "Public can read event tags" on public.event_tags;
create policy "Public can read event tags" on public.event_tags
  for select to anon, authenticated using (
    exists (
      select 1 from public.events
      where events.slug = event_tags.event_slug and events.published
    )
  );
drop policy if exists "Public can read links" on public.links;
create policy "Public can read links" on public.links
  for select to anon, authenticated using (true);

grant select on public.projects, public.technologies, public.project_technologies,
  public.experience_technologies, public.project_images, public.experiences,
  public.events, public.event_tags, public.links to anon, authenticated;

